import AppKit

/// Watches the system clipboard. macOS has no "clipboard changed" notification,
/// so this checks the pasteboard's change counter twice a second.
@MainActor
final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private let store: ClipStore
    private let settings: Settings
    private var lastChangeCount: Int
    private var timer: Timer?

    private static let maxTextLength = 2_000_000
    private static let maxRichTextBytes = 2 * 1024 * 1024

    /// Markers password managers and other apps put on content that shouldn't be saved.
    /// See nspasteboard.org.
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ].reduce(into: []) { $0.insert(NSPasteboard.PasteboardType($1)) }

    init(store: ClipStore, settings: Settings) {
        self.store = store
        self.settings = settings
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call after ClipKeep writes to the clipboard so its own paste isn't recorded again.
    func skipCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    private func check() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard settings.recording else { return }

        let types = Set(pasteboard.types ?? [])
        if settings.ignoreConcealed, !types.isDisjoint(with: Self.privateTypes) { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let bundleID = app?.bundleIdentifier {
            if bundleID == Bundle.main.bundleIdentifier || settings.isExcluded(bundleID) { return }
        }

        guard let text = pasteboard.string(forType: .string),
              text.utf16.count <= Self.maxTextLength,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }

        store.add(
            text: text,
            rtf: richText(),
            sourceBundleID: app?.bundleIdentifier,
            sourceName: app?.localizedName,
            limit: settings.historyLimit)
    }

    /// RTF if the copy has it; otherwise HTML converted to RTF (web pages usually copy as HTML).
    private func richText() -> Data? {
        if let rtf = pasteboard.data(forType: .rtf) {
            return rtf.count <= Self.maxRichTextBytes ? rtf : nil
        }
        guard let html = pasteboard.data(forType: .html), html.count <= Self.maxRichTextBytes,
              let attributed = NSAttributedString(html: html, documentAttributes: nil),
              let rtf = attributed.rtf(from: NSRange(location: 0, length: attributed.length))
        else { return nil }
        return rtf.count <= Self.maxRichTextBytes ? rtf : nil
    }
}
